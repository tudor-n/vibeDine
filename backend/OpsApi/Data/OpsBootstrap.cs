using Microsoft.EntityFrameworkCore;
using OpsApi.Auth;
using OpsApi.Models;

namespace OpsApi.Data;

/// <summary>
/// Creates the `ops_*` tables idempotently and seeds a default ops admin. Runs once at startup.
/// The ops console never runs EF migrations — mirrors PlatformApi's PlatformBootstrap.
/// </summary>
public static class OpsBootstrap
{
    public static async Task InitializeAsync(IServiceProvider services)
    {
        var db = services.GetRequiredService<OpsDbContext>();
        var config = services.GetRequiredService<IConfiguration>();
        var hasher = services.GetRequiredService<IPasswordHasher>();
        var env = services.GetRequiredService<IHostEnvironment>();
        var logger = services.GetRequiredService<ILoggerFactory>().CreateLogger(nameof(OpsBootstrap));

        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS ops_admins (
                id            uuid PRIMARY KEY,
                email         text NOT NULL,
                full_name     text NOT NULL,
                password_hash text NOT NULL,
                is_active     boolean NOT NULL DEFAULT true,
                created_at    timestamptz NOT NULL DEFAULT now(),
                last_login_at timestamptz NULL
            );
            CREATE UNIQUE INDEX IF NOT EXISTS ix_ops_admins_email ON ops_admins (lower(email));

            CREATE TABLE IF NOT EXISTS ops_connections (
                id                   uuid PRIMARY KEY,
                provider             text NOT NULL,
                name                 text NOT NULL,
                role                 text NULL,
                token_cipher         text NOT NULL,
                token_kind           text NULL,
                account_label        text NULL,
                metadata_json        jsonb NULL,
                capabilities_json    jsonb NULL,
                status               text NOT NULL DEFAULT 'active',
                status_detail        text NULL,
                created_at           timestamptz NOT NULL DEFAULT now(),
                last_checked_at      timestamptz NULL,
                created_by_admin_id  uuid NOT NULL
            );

            CREATE TABLE IF NOT EXISTS ops_audit_log (
                id              uuid PRIMARY KEY,
                actor_admin_id  uuid NULL,
                actor_email     text NULL,
                action          text NOT NULL,
                provider        text NULL,
                connection_id   uuid NULL,
                target_type     text NULL,
                target_id       text NULL,
                summary         text NULL,
                detail_json     jsonb NULL,
                result          text NOT NULL DEFAULT 'success',
                created_at      timestamptz NOT NULL DEFAULT now()
            );
            CREATE INDEX IF NOT EXISTS ix_ops_audit_log_created_at ON ops_audit_log (created_at DESC);

            CREATE TABLE IF NOT EXISTS ops_log_archive (
                id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                connection_id   uuid NOT NULL,
                provider        text NOT NULL,
                project_id      text NULL,
                service_id      text NULL,
                environment_id  text NULL,
                deployment_id   text NULL,
                log_type        text NOT NULL,
                severity        text NULL,
                message         text NOT NULL,
                attributes_json jsonb NULL,
                "timestamp"     timestamptz NOT NULL,
                ingested_at     timestamptz NOT NULL DEFAULT now()
            );
            CREATE INDEX IF NOT EXISTS ix_ops_log_archive_deployment ON ops_log_archive (deployment_id, "timestamp" DESC);
            CREATE INDEX IF NOT EXISTS ix_ops_log_archive_connection ON ops_log_archive (connection_id, "timestamp" DESC);
            """);

        if (!await db.Admins.AnyAsync())
        {
            var email = config["OpsSeed:Email"] ?? "ops@vibedine.local";
            var password = config["OpsSeed:Password"];

            // Never seed a login-able super-admin with a missing/empty or the committed default password.
            // (Program.cs already fail-fasts on this outside Development; this is defense-in-depth and also
            // guards the Development path where the fail-fast does not run.)
            if (string.IsNullOrWhiteSpace(password) || (!env.IsDevelopment() && password == "ChangeMe123!"))
            {
                logger.LogWarning(
                    "No ops admin seeded: OpsSeed:Password is not configured with a real secret. " +
                    "Set OpsSeed__Password to bootstrap the first admin.");
            }
            else
            {
                db.Admins.Add(new OpsAdmin
                {
                    Email = email,
                    FullName = "Ops Admin",
                    PasswordHash = hasher.Hash(password),
                });
                await db.SaveChangesAsync();
                logger.LogInformation("Seeded initial ops admin {Email}.", email);
            }
        }
    }
}
