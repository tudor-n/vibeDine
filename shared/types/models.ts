export type UUID = string;
export type ISODateString = string;

export interface Category {
  id: UUID;
  name: string;
  sortOrder: number | null;
}

export interface Product {
  id: UUID;
  categoryId: UUID;
  categoryName?: string;
  name: string;
  description: string;
  price: number;
  imageUrl: string | null;
  isAvailable: boolean;
}


export interface RestaurantTable {
  id: UUID;
  tableNumber: string | null;
  qrToken: UUID | null;
}

export interface TableSession {
  tableId: UUID;
  orderId: UUID;
  sessionToken: string;
}


export type OrderStatus = 'draft' | 'submitted' | 'preparing' | 'ready' | 'completed' | 'cancelled';
export type PaymentStatus = 'unpaid' | 'paid' | 'refunded';

export interface OrderItem {
  id: UUID;
  orderId: UUID;
  productId: UUID;
  product: Pick<Product, 'id' | 'name' | 'price' | 'imageUrl'>;
  quantity: number;
  unitPriceAtPurchase: number;
  wasAiRecommended: boolean;
  isFlashDealItem: boolean;
}

export interface Order {
  id: UUID;
  tableId: UUID;
  status: OrderStatus;
  paymentStatus: PaymentStatus;
  totalAmount: number;
  items: OrderItem[];
  createdAt: ISODateString;
}

export interface CartItem {
  product: Product;
  quantity: number;
}


export type FlashDealStatus = 'pending' | 'claimed' | 'expired';
export type FlashDealTrigger = 'post_order' | 'time_based' | 'slow_item';

export interface FlashDeal {
  id: UUID;
  menuItemId: UUID;
  menuItem: Pick<Product, 'id' | 'name' | 'price' | 'imageUrl'>;
  discountPercent: number;
  discountedPrice: number;
  trigger: FlashDealTrigger;
  countdownSeconds: number;
  expiresAt: ISODateString;
  reason: string;
  isActive: boolean;
  createdAt: ISODateString;
}


export type RecommendationType = 'pairing' | 'upsell' | 'flashDeal';
export type RecommendationReasonType =
  | 'chefPick'
  | 'pairsWithOrder'
  | 'popularCombo'
  | 'timeBased'
  | 'flashDeal';
export type RecommendationSource = 'ai' | 'manual' | 'ruleBased';

export interface Recommendation {
  id: UUID;
  type: RecommendationType;
  menuItem: Pick<Product, 'id' | 'name' | 'description' | 'price' | 'imageUrl' | 'categoryName'>;
  reason: string;
  reasonType: RecommendationReasonType;
  discount: {
    percent: number | null;
    originalPrice: number | null;
    discountedPrice: number | null;
  };
  confidence: number;
  source: RecommendationSource;
}


export interface FlashDealConfig {
  enabled: boolean;
  maxDealsPerSession: number;
  countdownSeconds: number;
  discountPercent: number;
}

export interface AdminAIConfig {
  id: UUID;
  date: ISODateString;
  dailyPrompt: string;
  promotedItems: UUID[];
  suppressedItems: UUID[];
  flashDealConfig: FlashDealConfig;
  createdBy: UUID;
  createdAt: ISODateString;
}

export interface AIDirective {
  id: UUID;
  rawPrompt: string | null;
  parsedRules: Record<string, unknown> | null;
  createdAt: ISODateString;
  isActive: boolean | null;
}


export type SimilarityRelationship = 'pairsWith' | 'upgradeTo' | 'followWith' | 'sameVibe';

export interface SimilarityRule {
  id: UUID;
  sourceItemId: UUID | null;
  sourceCategoryId: UUID | null;
  targetItemId: UUID;
  relationship: SimilarityRelationship;
  weight: number;
  isAutoGenerated: boolean;
  createdAt: ISODateString;
}


export interface DailyMetrics {
  date: ISODateString;
  flashDealsShown: number;
  flashDealsClaimed: number;
  recommendationClicks: number;
  upsellRevenue: number;
}